import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const base=process.argv[2]||'http://127.0.0.1:8787',out=process.argv[3]||'output/design';
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true}),errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});page.on('pageerror',e=>errors.push(e.message));
const pass=s=>console.log('PASS',s);
try{
 await page.goto(base+'/demo');
 const room=await page.evaluate(async()=>{const r=await fetch('/api/demo',{method:'POST',headers:{'content-type':'application/json'},body:'{}'});if(!r.ok)throw new Error('demo '+r.status);return r.json();});
 await page.evaluate(async token=>{const r=await fetch('/api/demo/'+token+'/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({role:'owner'})});if(!r.ok)throw new Error('session '+r.status);},room.token);
 await page.goto(base+'/app');await page.locator('.workspace-welcome').waitFor();
 await page.locator('[data-k=design]').click();await page.locator('.design-grid').waitFor();
 assert.equal(await page.locator('.design-card').count(),100);pass('studio lists 100 ready designs');
 await page.locator('[data-sector=seasonal]').click();assert.equal(await page.locator('.design-card').count(),4);
 const frame=page.frameLocator('#st-frame');await frame.locator('.menu-sheet').waitFor();
 await page.locator('[data-try=season-ramadan]').click();
 await page.waitForFunction(()=>document.querySelector('#st-frame').contentDocument?.documentElement.dataset.dLayout==='cards');
 pass('trying a design updates the live preview without saving');
 await page.locator('[data-sector=all]').click();await page.fill('#st-q','smash');assert.equal(await page.locator('.design-card').count(),4);
 await page.locator('[data-use=smash-grid]').click();await page.locator('.design-card.current').waitFor();
 await page.locator('[data-tab=custom]').click();await page.locator('.studio-step').first().waitFor();
 await page.locator('.studio-step').nth(4).locator('summary').click();await page.locator('label.opt:has(input[value=magazine])').click();
 await page.waitForFunction(()=>document.querySelector('#st-frame').contentDocument?.documentElement.dataset.dLayout==='magazine');
 await page.locator('.studio-step').nth(7).locator('summary').click();await page.locator('label.opt:has(input[value=neon])').click();
 await page.waitForTimeout(900);
 const d=await page.evaluate(async()=>(await (await fetch('/api/owner/design')).json()).draft);
 assert.equal(d.layout,'magazine');assert.equal(d.button.style,'neon');pass('custom steps autosave the draft');
 await page.screenshot({path:out+'/studio-desktop.png',fullPage:true});
 await page.locator('#st-publish').click();await page.getByText('نشرنا تصميمك').waitFor();
 const slug=(await page.evaluate(async()=>(await (await fetch('/api/owner/branches')).json()).branches[0].slug));
 const guest=await browser.newPage({viewport:{width:390,height:844}});guest.on('pageerror',e=>errors.push(e.message));
 await guest.goto(base+'/m/'+slug);await guest.locator('.menu-sheet').waitFor();
 assert.equal(await guest.evaluate(()=>document.documentElement.dataset.dLayout),'magazine');
 await guest.screenshot({path:out+'/guest-mobile.png',fullPage:true});pass('guests see the published design');
 await page.locator('[data-tab=versions]').click();await page.fill('#st-vname','رمضان');await page.locator('#st-vform [type=submit]').click();await page.getByText('حفظنا النسخة').waitFor();
 pass('named version saved');
 const narrow=await browser.newPage({viewport:{width:390,height:844}});
 await narrow.context().addCookies(await page.context().cookies());
 await narrow.goto(base+'/app');await narrow.locator('[data-k=design]').click();await narrow.locator('.design-grid').waitFor();
 assert.ok(await narrow.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'no horizontal scroll on phones');
 await narrow.screenshot({path:out+'/studio-mobile.png'});pass('studio fits a phone screen');
 assert.deepEqual(errors,[]);
}finally{await browser.close();}
